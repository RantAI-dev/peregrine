#!/usr/bin/env python3
"""Regenerate crates/peregrine-core/src/unicode_data.rs from a llama.cpp checkout.

Peregrine carries no Unicode tables of its own and no dependency may provide them
(ADR 0002). The WordPiece tokenizer needs four of llama.cpp's generated tables --
the category flags (whitespace, control, punctuation, symbol, accent mark), the
White_Space set, the lowercase map and the accent-stripping map -- so they are
transcribed here, table for table, from the release the tokenizers are checked
against:

    src/unicode-data.cpp   llama.cpp v0.9.0 (commit cd959ba)

Usage:

    git clone --depth 1 https://github.com/ggml-org/llama.cpp /var/tmp/llama.cpp
    python3 scripts/gen-unicode-tables.py /var/tmp/llama.cpp/src/unicode-data.cpp \\
        > crates/peregrine-core/src/unicode_data.rs

The source file is MIT licensed (Copyright the ggml authors); see NOTICE.
"""

import re
import sys


def block(src: str, name: str) -> str:
    i = src.index(name)
    i = src.index("{", src.index("=", i))
    depth = 0
    for j in range(i, len(src)):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                return src[i + 1 : j]
    raise SystemExit(f"unterminated block for {name}")


def pairs(body: str):
    nums = re.findall(r"0x([0-9A-Fa-f]+)", body)
    assert len(nums) % 2 == 0, len(nums)
    for k in range(0, len(nums), 2):
        yield int(nums[k], 16), int(nums[k + 1], 16)


def triples(body: str):
    nums = re.findall(r"0x([0-9A-Fa-f]+)", body)
    assert len(nums) % 3 == 0, len(nums)
    for k in range(0, len(nums), 3):
        yield int(nums[k], 16), int(nums[k + 1], 16), int(nums[k + 2], 16)


def main(path: str) -> None:
    src = open(path, encoding="utf-8").read()
    flags = list(pairs(block(src, "unicode_ranges_flags")))
    # The whitespace set is a flat list of code points.
    white = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", block(src, "unicode_set_whitespace"))]
    lower = list(pairs(block(src, "unicode_map_lowercase")))
    nfd = list(triples(block(src, "unicode_ranges_nfd")))

    out = []
    w = out.append
    w("//! Unicode tables for the WordPiece tokenizer, transcribed from llama.cpp.")
    w("//!")
    w("//! Generated by `scripts/gen-unicode-tables.py` from llama.cpp v0.9.0")
    w("//! (commit cd959ba) `src/unicode-data.cpp`; do not edit by hand. The source is")
    w("//! MIT licensed (Copyright the ggml authors) and generated in turn from the")
    w("//! Unicode Character Database. Peregrine's tokenizers must agree with llama.cpp")
    w("//! code point for code point, so the tables are copied rather than re-derived")
    w("//! from a different Unicode version: `char::is_alphabetic` and friends are the")
    w("//! wrong property (see the module docs in `tokenizer.rs`).")
    w("")
    w("#![allow(dead_code)] // not every category is needed by every tokenizer")
    w("")
    w("/// Category bits, as `unicode_cpt_flags` in llama.cpp's `src/unicode.h`.")
    w("pub(crate) const UNDEFINED: u16 = 0x0001;")
    w("pub(crate) const NUMBER: u16 = 0x0002;")
    w("pub(crate) const LETTER: u16 = 0x0004;")
    w("pub(crate) const SEPARATOR: u16 = 0x0008;")
    w("pub(crate) const ACCENT_MARK: u16 = 0x0010;")
    w("pub(crate) const PUNCTUATION: u16 = 0x0020;")
    w("pub(crate) const SYMBOL: u16 = 0x0040;")
    w("pub(crate) const CONTROL: u16 = 0x0080;")
    w("pub(crate) const WHITESPACE: u16 = 0x0100;")
    w("")
    w("/// `unicode_ranges_flags`: `(start, flags)`, where a range runs to the next")
    w("/// start minus one. The last entry is the sentinel at `0x110000`.")
    w("pub(crate) static RANGES_FLAGS: &[(u32, u16)] = &[")
    for start, f in flags:
        w(f"    (0x{start:06X}, 0x{f:04X}),")
    w("];")
    w("")
    w("/// `unicode_set_whitespace`: the code points with the `White_Space` property.")
    w("pub(crate) static WHITESPACE_SET: &[u32] = &[")
    for c in white:
        w(f"    0x{c:06X},")
    w("];")
    w("")
    w("/// `unicode_map_lowercase`: `(from, to)` for the simple lowercase mapping.")
    w("pub(crate) static LOWERCASE: &[(u32, u32)] = &[")
    for a, b in lower:
        w(f"    (0x{a:06X}, 0x{b:06X}),")
    w("];")
    w("")
    w("/// `unicode_ranges_nfd`: `(first, last, base)`. llama.cpp's accent")
    w("/// stripping maps a precomposed character to the base letter in one pass")
    w("/// rather than expanding a full canonical decomposition.")
    w("pub(crate) static NFD_RANGES: &[(u32, u32, u32)] = &[")
    for a, b, c in nfd:
        w(f"    (0x{a:06X}, 0x{b:06X}, 0x{c:06X}),")
    w("];")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
